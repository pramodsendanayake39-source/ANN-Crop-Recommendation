def recommend_crop(N, P, K, temperature, humidity, ph, rainfall):

    # Create a table containing the new input values
    new_data = pd.DataFrame({
        'N': [N],
        'P': [P],
        'K': [K],
        'temperature': [temperature],
        'humidity': [humidity],
        'ph': [ph],
        'rainfall': [rainfall]
    })

    # Scale the input using the same scaler used during training
    new_data_scaled = scaler.transform(new_data)

    # Ask the ANN to make a prediction
    prediction = model.predict(
        new_data_scaled,
        verbose=0
    )

    # Find the class with the highest probability
    predicted_class = np.argmax(prediction, axis=1)

    # Convert the class number back to the crop name
    predicted_crop = label_encoder.inverse_transform(
        predicted_class
    )[0]

    # Get the probability of the selected crop
    confidence = np.max(prediction) * 100

    # Display the result
    print("Recommended Crop:", predicted_crop)
    print("Confidence:", round(confidence, 2), "%")

