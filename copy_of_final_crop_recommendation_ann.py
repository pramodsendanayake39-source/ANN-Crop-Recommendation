import gradio as gr
import pandas as pd
import numpy as np
import joblib

from tensorflow import keras
from google.colab import drive

drive.mount('/content/drive')

project_folder = '/content/drive/MyDrive/ANN_Crop_Project'

model = keras.models.load_model(
    project_folder + '/final_crop_recommendation_ann.keras'
)

scaler = joblib.load(
    project_folder + '/crop_scaler.pkl'
)

label_encoder = joblib.load(
    project_folder + '/crop_label_encoder.pkl'
)

print("✅ Model, scaler and label encoder loaded successfully!")

def predict_crop(
    nitrogen,
    phosphorus,
    potassium,
    temperature,
    humidity,
    ph,
    rainfall
):

    # -----------------------------------------
    # Check whether all input values are entered
    # -----------------------------------------

    values = [
        nitrogen,
        phosphorus,
        potassium,
        temperature,
        humidity,
        ph,
        rainfall
    ]

    if any(value is None for value in values):

        warning = """
        <div class="warning-card">
            ⚠️ Please enter values for all seven parameters
            before requesting a crop recommendation.
        </div>
        """

        return warning, {}


    # -----------------------------------------
    # Basic input validation
    # -----------------------------------------

    if (
        nitrogen < 0 or nitrogen > 140 or
        phosphorus < 5 or phosphorus > 145 or
        potassium < 5 or potassium > 205 or
        temperature < 8 or temperature > 44 or
        humidity < 14 or humidity > 100 or
        ph < 3.5 or ph > 10 or
        rainfall < 20 or rainfall > 300
    ):

        warning = """
        <div class="warning-card">
            ⚠️ One or more values are outside the approximate
            range represented in the training dataset.
            Please check the entered values.
        </div>
        """

        return warning, {}


    # -----------------------------------------
    # Create input dataframe
    # -----------------------------------------

    input_data = pd.DataFrame({
        'N': [nitrogen],
        'P': [phosphorus],
        'K': [potassium],
        'temperature': [temperature],
        'humidity': [humidity],
        'ph': [ph],
        'rainfall': [rainfall]
    })


    # -----------------------------------------
    # Apply training scaler
    # -----------------------------------------

    input_scaled = scaler.transform(input_data)


    # -----------------------------------------
    # ANN prediction
    # -----------------------------------------

    probabilities = model.predict(
        input_scaled,
        verbose=0
    )[0]


    # -----------------------------------------
    # Highest probability crop
    # -----------------------------------------

    predicted_index = np.argmax(probabilities)

    predicted_crop = label_encoder.inverse_transform(
        [predicted_index]
    )[0]

    confidence = probabilities[predicted_index] * 100


    # -----------------------------------------
    # Top 3 crop predictions
    # -----------------------------------------

    top3_indices = np.argsort(
        probabilities
    )[-3:][::-1]

    top3_results = {}

    for index in top3_indices:

        crop_name = label_encoder.inverse_transform(
            [index]
        )[0]

        top3_results[crop_name] = float(
            probabilities[index]
        )


    # -----------------------------------------
    # Confidence description
    # -----------------------------------------

    if confidence >= 90:
        confidence_text = "Very High Model Confidence"

    elif confidence >= 70:
        confidence_text = "High Model Confidence"

    elif confidence >= 50:
        confidence_text = "Moderate Model Confidence"

    else:
        confidence_text = "Low Model Confidence"


    # -----------------------------------------
    # Attractive output card
    # -----------------------------------------

    result_html = f"""
    <div class="result-card">

        <div class="result-icon">
            🌱
        </div>

        <div class="result-small-title">
            ANN RECOMMENDATION
        </div>

        <div class="recommended-label">
            Recommended Crop
        </div>

        <div class="crop-name">
            {predicted_crop.title()}
        </div>

        <div class="confidence-container">

            <div class="confidence-title">
                Model Confidence
            </div>

            <div class="confidence-value">
                {confidence:.2f}%
            </div>

            <div class="confidence-description">
                {confidence_text}
            </div>

        </div>

        <div class="result-note">
            Recommendation generated using soil nutrient
            and climatic conditions supplied by the user.
        </div>

    </div>
    """

    return result_html, top3_results

